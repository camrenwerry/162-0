export const RELEASE_INSPECTION_MANIFEST_PATH = 'config/release-inspection-manifest.json'

const IDENTITY_CAPABILITIES = new Set([
  'identityClaim',
  'identityStatus',
  'identityRename',
  'identityRecovery',
])

// Independently authored applicability expectations. This is deliberately not
// generated by filtering the runtime descriptor registry.
export const EXPECTED_RELEASE_INSPECTION_SURFACES = RELEASE_INSPECTION_CAPABILITY_SURFACES

function fail(message) {
  throw new TypeError(`Local release-inspection projection refused: ${message}`)
}

function evidence(availability, provenance, sourcePath = null, sourceHash = null) {
  return immutablePlain({ availability, provenance, sourceHash, sourcePath })
}

function sourceEvidence(provenance, sourcePath, hashes) {
  const sourceHash = hashes.get(sourcePath)
  if (!sourceHash) fail(`missing provenance hash for ${sourcePath}.`)
  return evidence('available', provenance, sourcePath, sourceHash)
}

function notApplicableEvidence() {
  return evidence('not-applicable', 'not-applicable')
}

function surfaceState({ applicable, configuredState, provenance, sourcePath, hashes }) {
  if (!applicable) {
    return immutablePlain({
      applicability: 'not-applicable',
      configuredState: 'not-applicable',
      effectiveState: 'not-applicable',
      evidence: notApplicableEvidence(),
    })
  }
  return immutablePlain({
    applicability: 'applicable',
    configuredState,
    effectiveState: 'disabled',
    evidence: sourceEvidence(provenance, sourcePath, hashes),
  })
}

function trustedSourceContext(hashes) {
  return {
    protectedSourceHashes: RELEASE_INSPECTION_PROTECTED_SOURCE_PATHS.map((sourcePath) => ({
      path: sourcePath,
      sha256: hashes.get(sourcePath),
    })),
  }
}

function expectedVariable(readiness, capability, surface) {
  const registrySurface = surface === 'pages' ? 'pagesFunctions' : 'privateWorker'
  return readiness.capabilityVariables[capability][registrySurface]
}

function buildCapabilityMatrix({ authorityModel, readiness, frontendSource, pagesVariables, workerVariables, hashes, manifest }) {
  const environments = {}
  for (const environment of SCHEMA4_ENVIRONMENTS) {
    const authority = authorityModel.environments[environment]
    const pageValues = pagesVariables[environment]
    const workerValues = workerVariables[environment]
    const capabilities = {}
    for (const capability of SCHEMA4_CAPABILITIES) {
      const applicableSurfaces = new Set(EXPECTED_RELEASE_INSPECTION_SURFACES[capability])
      const pageVariable = expectedVariable(readiness, capability, 'pages')
      const workerVariable = expectedVariable(readiness, capability, 'worker')
      const surfaceValues = {
        frontend: frontendSource.capabilities[capability],
        pages: pageVariable === null ? 'not-applicable' : pageValues.get(pageVariable),
        worker: workerVariable === null ? 'not-applicable' : workerValues.get(workerVariable),
        schedule: capability === 'cleanupCron' ? 'disabled' : 'not-applicable',
      }
      for (const surface of RELEASE_INSPECTION_SURFACES) {
        const expectedApplicable = applicableSurfaces.has(surface)
        if (expectedApplicable && surfaceValues[surface] !== 'disabled') {
          fail(`${environment}.${capability}.${surface} must be configured disabled.`)
        }
        if (!expectedApplicable && surfaceValues[surface] !== 'not-applicable'
          && !(surface === 'frontend' && capability === 'cleanupCron' && surfaceValues[surface] === 'disabled')) {
          fail(`${environment}.${capability}.${surface} applicability is inconsistent.`)
        }
      }
      capabilities[capability] = {
        authority: {
          configuredState: authority.capabilities[capability],
          evidence: sourceEvidence('local-authority', manifest.sources.authority, hashes),
        },
        compatibilityCeiling: IDENTITY_CAPABILITIES.has(capability)
          ? authority.identityCompatibilityMode
          : 'not-applicable',
        emergencyStopInfluence: 'forced-disabled',
        effectiveState: 'disabled',
        surfaces: {
          frontend: surfaceState({
            applicable: applicableSurfaces.has('frontend'),
            configuredState: surfaceValues.frontend,
            provenance: 'protected-frontend',
            sourcePath: manifest.sources.frontendCapabilities,
            hashes,
          }),
          pages: surfaceState({
            applicable: applicableSurfaces.has('pages'),
            configuredState: surfaceValues.pages,
            provenance: 'local-configuration',
            sourcePath: manifest.sources.pagesConfiguration,
            hashes,
          }),
          worker: surfaceState({
            applicable: applicableSurfaces.has('worker'),
            configuredState: surfaceValues.worker,
            provenance: 'local-configuration',
            sourcePath: manifest.sources.workerConfiguration,
            hashes,
          }),
          schedule: surfaceState({
            applicable: applicableSurfaces.has('schedule'),
            configuredState: surfaceValues.schedule,
            provenance: 'local-configuration',
            sourcePath: manifest.sources.workerConfiguration,
            hashes,
          }),
        },
      }
    }
    environments[environment] = {
      authorityContext: {
        environment,
        reviewedAtMs: authority.reviewedAtMs,
        expiresAtMs: authority.expiresAtMs,
        emergencyStop: authority.emergencyStop,
        identityCompatibilityCeiling: authority.identityCompatibilityMode,
        evidence: sourceEvidence('local-authority', manifest.sources.authority, hashes),
      },
      capabilities,
    }
  }
  return validateCapabilityMatrix({
    schemaVersion: RELEASE_INSPECTION_SCHEMA_VERSION,
    kind: RELEASE_INSPECTION_KINDS.capabilityMatrix,
    environments,
  }, trustedSourceContext(hashes))
}

function sortedBindings(bindings) {
  return [...bindings].sort((left, right) => left.name.localeCompare(right.name))
}

function variableBindings(variables) {
  return [...variables.entries()].map(([name, value]) => ({ name, type: 'plain-text', value }))
}

function d1Binding(table) {
  return { name: table.binding, type: 'd1', value: `${table.database_name}:${table.database_id}` }
}

function serviceBinding(table) {
  return { name: table.binding, type: 'service', value: table.service }
}

function rateBindings(tables) {
  return tables.map(({ name, namespaceId }) => ({ name, type: 'rate-limit', value: namespaceId }))
}

function buildBindingPolicy({ manifest, legacyManifest, pagesTopology, workerTopology, pagesVariables, workerVariables, hashes }) {
  const preview = legacyManifest.cloudflare.preview
  const production = legacyManifest.cloudflare.production
  const pagesD1 = {
    preview: pagesTopology.environments.preview.d1,
    production: pagesTopology.environments.production.d1,
  }
  const pagesService = {
    preview: pagesTopology.environments.preview.service,
    production: pagesTopology.environments.production.service,
  }
  const workerD1 = workerTopology.environments.preview.d1
  const workerRates = {
    preview: workerTopology.environments.preview.rateLimits,
    production: workerTopology.environments.production.rateLimits,
  }
  const expectedD1 = {
    preview: preview.d1,
    production: production.d1,
  }
  for (const environment of SCHEMA4_ENVIRONMENTS) {
    const table = pagesD1[environment]
    const expected = expectedD1[environment]
    if (table.binding !== expected.binding || table.database_id !== expected.id || table.database_name !== expected.name) {
      fail(`${environment} Pages D1 binding differs from reviewed identity.`)
    }
    const service = pagesService[environment]
    const expectedService = legacyManifest.cloudflare[environment].worker.serviceBinding
    if (service.binding !== expectedService.binding || service.service !== expectedService.service) {
      fail(`${environment} Pages Service Binding differs from reviewed identity.`)
    }
  }
  if (workerD1.binding !== preview.d1.binding
    || workerD1.database_id !== preview.d1.id
    || workerD1.database_name !== preview.d1.name) fail('Preview Worker D1 differs from reviewed identity.')
  if (workerTopology.environments.production.d1 !== null) fail('Production Worker D1 binding is forbidden.')
  if (pagesTopology.projectName !== preview.pages.project
    || pagesTopology.projectName !== production.pages.project) {
    fail('Pages project identity differs from reviewed local identity.')
  }
  if (workerTopology.environments.preview.name !== preview.worker.name
    || workerTopology.environments.production.name !== production.worker.name) {
    fail('Worker identity differs from reviewed local identity.')
  }
  for (const environment of SCHEMA4_ENVIRONMENTS) {
    const topology = workerTopology.environments[environment]
    if (topology.workersDev !== false || topology.previewUrls !== false
      || topology.routes.length !== 0 || topology.customDomains.length !== 0) {
      fail(`${environment} Worker public exposure is forbidden.`)
    }
  }
  const pagesOutput = pagesTopology.buildOutputDirectory
  if (pagesOutput !== 'dist') fail('Pages build output directory must remain dist.')

  const environments = {}
  for (const environment of SCHEMA4_ENVIRONMENTS) {
    const pagesBindings = sortedBindings([
      ...variableBindings(pagesVariables[environment]),
      d1Binding(pagesD1[environment]),
      serviceBinding(pagesService[environment]),
    ])
    const workerBindings = sortedBindings([
      ...variableBindings(workerVariables[environment]),
      ...(environment === 'preview' ? [d1Binding(workerD1)] : []),
      ...rateBindings(workerRates[environment]),
    ])
    environments[environment] = {
      frontend: {
        bindings: [],
        publicExposure: {
          customDomains: null,
          evidenceStatus: 'not-applicable',
          previewUrls: 'not-applicable',
          routes: null,
          workersDev: 'not-applicable',
        },
        schedules: { policy: 'not-applicable', values: [] },
        secretPolicies: manifest.secretPolicies[environment].frontend,
      },
      pages: {
        bindings: pagesBindings,
        publicExposure: {
          customDomains: null,
          evidenceStatus: 'unavailable',
          previewUrls: 'not-applicable',
          routes: null,
          workersDev: 'not-applicable',
        },
        schedules: { policy: 'not-applicable', values: [] },
        secretPolicies: manifest.secretPolicies[environment].pages,
      },
      platformPrerequisites: {
        pages: {
          DRAFT_TICKET_MODE: pagesVariables[environment].get('DRAFT_TICKET_MODE'),
          DRAFT_VALIDATION_MODE: pagesVariables[environment].get('DRAFT_VALIDATION_MODE'),
        },
        worker: {
          DRAFT_TICKET_MODE: workerVariables[environment].get('DRAFT_TICKET_MODE'),
          DRAFT_VALIDATION_MODE: workerVariables[environment].get('DRAFT_VALIDATION_MODE'),
        },
      },
      providerBuildSettings: {
        localEvidence: {
          pagesBuildOutputDirectory: pagesOutput,
          pagesCompatibilityDate: pagesTopology.compatibilityDate,
          pagesD1Configuration: {
            migrationsDirectory: pagesD1[environment].migrations_dir,
            previewDatabaseId: pagesD1[environment].preview_database_id ?? null,
          },
          pagesProjectName: pagesTopology.projectName,
          protectedFrontendSource: manifest.providerBuildPolicy.protectedFrontendSource,
          redirectsHash: hashes.get(manifest.sources.redirects),
          routesHash: hashes.get(manifest.sources.routes),
          workerCompatibilityDate: workerTopology.compatibilityDate,
          workerD1Configuration: workerTopology.environments[environment].d1 === null
            ? null
            : {
              migrationsDirectory: workerTopology.environments[environment].d1.migrations_dir,
              previewDatabaseId: workerTopology.environments[environment].d1.preview_database_id ?? null,
            },
          workerMain: workerTopology.main,
          workerName: workerTopology.environments[environment].name,
          workerRateLimits: workerTopology.environments[environment].rateLimits,
        },
        remoteEvidence: 'unavailable',
      },
      schedule: {
        bindings: [],
        publicExposure: {
          customDomains: null,
          evidenceStatus: 'not-applicable',
          previewUrls: 'not-applicable',
          routes: null,
          workersDev: 'not-applicable',
        },
        schedules: { policy: 'exact-empty', values: workerTopology.environments[environment].crons },
        secretPolicies: manifest.secretPolicies[environment].schedule,
      },
      worker: {
        bindings: workerBindings,
        publicExposure: {
          customDomains: workerTopology.environments[environment].customDomains,
          evidenceStatus: 'local-configuration',
          previewUrls: workerTopology.environments[environment].previewUrls,
          routes: workerTopology.environments[environment].routes,
          workersDev: workerTopology.environments[environment].workersDev,
        },
        schedules: { policy: 'exact-empty', values: workerTopology.environments[environment].crons },
        secretPolicies: manifest.secretPolicies[environment].worker,
      },
    }
  }
  return validateBindingPolicy({
    schemaVersion: RELEASE_INSPECTION_SCHEMA_VERSION,
    kind: RELEASE_INSPECTION_KINDS.bindingPolicy,
    environments,
  }, trustedSourceContext(hashes))
}

export function loadReleaseInspectionManifest(repositoryRoot) {
  const source = readBoundedUtf8File(path.join(repositoryRoot, RELEASE_INSPECTION_MANIFEST_PATH), {
    label: 'Release-inspection manifest',
    maxBytes: STRICT_JSON_LIMITS.releaseManifest.maxBytes,
  })
  return parseReleaseInspectionManifest(source)
}

function protectedHashes(repositoryRoot, manifest) {
  const migrations = loadRepositoryMigrations(repositoryRoot, manifest.sources.migrationsDirectory)
  const paths = [...new Set([
    ...PROTECTED_CONFIGURATION_PATHS,
    RELEASE_INSPECTION_MANIFEST_PATH,
    'src/config/protectedCapabilities.mjs',
    'src/config/protectedCapabilities.d.mts',
    manifest.sources.redirects,
    manifest.sources.routes,
    ...migrations.map(({ name }) => `${manifest.sources.migrationsDirectory}/${name}`),
  ])].sort()
  if (canonicalJson(paths) !== canonicalJson(RELEASE_INSPECTION_PROTECTED_SOURCE_PATHS)) {
    fail('protected provenance paths differ from the exact reviewed source inventory.')
  }
  const entries = paths.map((relativePath) => ({
    path: relativePath,
    sha256: fileHash(path.join(repositoryRoot, relativePath)),
  }))
  return {
    entries: immutablePlain(entries),
    map: new Map(entries.map(({ path: relativePath, sha256 }) => [relativePath, sha256])),
  }
}

function loadLocalSources(repositoryRoot, manifest, nowMs) {
  const readiness = loadSchema4ReadinessModel(repositoryRoot)
  const registrations = loadSchema4RuntimeConsumerRegistrations(repositoryRoot)
  validateSchema4RuntimeGateRegistry(SCHEMA4_RUNTIME_GATE_REGISTRY, registrations)
  const authoritySource = readBoundedUtf8File(path.join(repositoryRoot, manifest.sources.authority), {
    label: 'Schema-4 capability model',
    maxBytes: STRICT_JSON_LIMITS.authorityModel.maxBytes,
  })
  const pagesSource = readBoundedUtf8File(path.join(repositoryRoot, manifest.sources.pagesConfiguration), {
    label: 'Pages configuration',
    maxBytes: STRICT_JSON_LIMITS.releaseManifest.maxBytes,
  })
  const workerSource = readBoundedUtf8File(path.join(repositoryRoot, manifest.sources.workerConfiguration), {
    label: 'Worker configuration',
    maxBytes: STRICT_JSON_LIMITS.releaseManifest.maxBytes,
  })
  const authorityModel = parseSchema4CapabilityModel(authoritySource, nowMs)
  validateProtectedCapabilityFoundation({
    capabilityModelSource: authoritySource,
    pagesConfig: pagesSource,
    workerConfig: workerSource,
  }, { repositoryRoot, nowMs, readiness })
  const frontendSource = validateProtectedFrontendCapabilitySource(
    PROTECTED_FRONTEND_CAPABILITY_SOURCE,
  )
  if (readiness.frontendBuildTime.protectedSource !== manifest.sources.frontendCapabilities
    || SCHEMA4_RUNTIME_GATE_REGISTRY.frontendBuildTime.protectedSource !== manifest.sources.frontendCapabilities) {
    fail('protected frontend source differs across manifest, readiness, and registry.')
  }
  return {
    authorityModel,
    frontendSource,
    legacyManifest: loadReleaseManifest(repositoryRoot).manifest,
    pagesSource,
    readiness,
    workerSource,
  }
}

export const loadLocalReleaseInspectionSources = loadLocalSources

export function createLocalReleaseInspectionProjection(options = {}) {
  const {
    repositoryRoot,
    requestedCapabilities = createAllDisabledCapabilityTarget(),
    nowMs,
    sourceLoader = loadLocalSources,
  } = options
  // Policy validation intentionally precedes every filesystem read and every
  // optional dependency initialization.
  validateCapabilityTarget(requestedCapabilities)
  if (typeof repositoryRoot !== 'string' || !path.isAbsolute(repositoryRoot)) {
    fail('repository root must be one absolute path.')
  }
  const resolvedNowMs = nowMs === undefined ? Date.now() : nowMs
  const manifest = loadReleaseInspectionManifest(repositoryRoot)
  const hashes = protectedHashes(repositoryRoot, manifest)
  const sources = sourceLoader(repositoryRoot, manifest, resolvedNowMs)
  const pagesTopology = inspectPagesWranglerTopology(sources.pagesSource)
  const workerTopology = inspectWorkerWranglerTopology(sources.workerSource)
  const pagesVariables = Object.fromEntries(SCHEMA4_ENVIRONMENTS.map((environment) => [
    environment,
    new Map(Object.entries(pagesTopology.environments[environment].variables)),
  ]))
  const workerVariables = Object.fromEntries(SCHEMA4_ENVIRONMENTS.map((environment) => [
    environment,
    new Map(Object.entries(workerTopology.environments[environment].variables)),
  ]))
  const capabilityMatrix = buildCapabilityMatrix({
    authorityModel: sources.authorityModel,
    readiness: sources.readiness,
    frontendSource: sources.frontendSource,
    pagesVariables,
    workerVariables,
    hashes: hashes.map,
    manifest,
  })
  const bindingPolicy = buildBindingPolicy({
    manifest,
    legacyManifest: sources.legacyManifest,
    pagesTopology,
    workerTopology,
    pagesVariables,
    workerVariables,
    hashes: hashes.map,
  })
  const remoteObservation = validateObservationPlaceholder({
    schemaVersion: RELEASE_INSPECTION_SCHEMA_VERSION,
    kind: RELEASE_INSPECTION_KINDS.observationPlaceholder,
    environments: {
      preview: {
        status: 'unavailable',
        reason: 'identity-grounding-required',
        currentness: 'unknown',
      },
      production: {
        status: 'unavailable',
        reason: 'production-remote-inspection-excluded',
        currentness: 'unknown',
      },
    },
  })
  return validateLocalProjection({
    schemaVersion: RELEASE_INSPECTION_SCHEMA_VERSION,
    kind: RELEASE_INSPECTION_KINDS.localProjection,
    toolContractVersion: RELEASE_INSPECTION_TOOL_CONTRACT_VERSION,
    policy: 'all-disabled',
    manifestHash: hashes.map.get(RELEASE_INSPECTION_MANIFEST_PATH),
    authorityHash: hashes.map.get(manifest.sources.authority),
    protectedSourceHashes: hashes.entries,
    capabilityMatrix,
    bindingPolicy,
    remoteObservation,
    result: 'UNKNOWN',
    executionAuthorization: 'prohibited',
    noNetworkAccess: true,
    noFilesystemWrites: true,
  })
}

export function renderLocalReleaseInspectionProjection(projection) {
  return canonicalReleaseInspectionJson(validateLocalProjection(projection))
}
